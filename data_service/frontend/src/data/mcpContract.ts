  name: string
  group:
    | 'Core'
    | 'Distill'
    | 'Trace'
    | 'Quality'
    | 'V2 Envelope'
    | 'Workspace'
    | 'Source'
    | 'Build'
    | 'Session GraphRAG'
    | 'Project Intelligence'
